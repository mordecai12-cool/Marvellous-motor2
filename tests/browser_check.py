"""Local browser checks. Run after ./start-local.sh with playwright installed."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
BASE = 'http://127.0.0.1:8080'
checks, errors = [], []

def check(condition, label):
    assert condition, label
    checks.append(label)

def visible_ids(page):
    return page.locator('.catalogue-grid .vehicle-card:visible').evaluate_all('(cards) => cards.map(x => x.dataset.id)')

def screenshot(page, name):
    page.evaluate("document.querySelectorAll('img').forEach(image => image.loading = 'eager')")
    page.evaluate("Promise.race([Promise.all([...document.images].filter(i => i.getClientRects().length > 0).map(i => i.decode().catch(() => {}))), new Promise(resolve => setTimeout(resolve, 10000))])")
    page.screenshot(path=str(ROOT / '.local' / 'previews' / name), full_page=True)
    check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'{name}: no horizontal overflow')
    check(page.locator('img').evaluate_all('(images) => images.filter(i => i.getClientRects().length > 0).every(i => i.complete && i.naturalWidth > 0)'), f'{name}: all images loaded')

with sync_playwright() as pw:
    browser = pw.chromium.launch(executable_path='/usr/bin/google-chrome', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':1440,'height':1000})
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE, wait_until='networkidle')
    inventory = context.request.get(BASE+'/api/vehicles').json()
    check(len(inventory)==16,'Vehicle API exposes all 16 sample listings')
    screenshot(page,'home-desktop.png')
    page.locator('[data-featured-filter="Used"]').click()
    check(page.locator('.featured-grid .vehicle-card:visible').count()==2,'Featured condition tabs work')
    page.locator('[data-featured-filter=""]').click()
    page.locator('[data-save="mercedes-c300"]').click()
    page.reload(wait_until='networkidle')
    check(page.locator('[data-save="mercedes-c300"]').get_attribute('aria-pressed')=='true','Saved vehicle survives reload')
    page.locator('[data-compare="mercedes-c300"]').check()
    page.locator('[data-compare="toyota-camry"]').check()
    page.locator('#open-compare').click()
    page.locator('#compare-dialog[open]').wait_for()
    check('Mercedes-Benz C 300' in page.locator('#compare-content').inner_text() and 'Toyota Camry' in page.locator('#compare-content').inner_text(),'Comparison shows the selected cars and specifications')
    page.locator('.dialog-close').click()
    page.locator('#clear-compare').click()
    page.goto(BASE+'/cars.html',wait_until='networkidle')
    check(len(visible_ids(page))==9,'Catalogue paginates at 9 vehicles')
    page.locator('#next-page').click()
    check(len(visible_ids(page))==7 and 'page=2' in page.url,'Second page works and URL retains page')
    page.locator('input[name="q"]').fill('Toyota')
    check(int(page.locator('#results-count').inner_text())==5,'Search filters by make')
    page.locator('select[name="condition"]').select_option('Used')
    check(int(page.locator('#results-count').inner_text())==3,'Search and condition filters combine')
    page.locator('button[type="reset"]').click()
    page.wait_for_timeout(60)
    page.locator('select[name="body"]').select_option('SUV')
    page.locator('select[name="budget"]').select_option('100000000')
    expected=sum(v['body']=='SUV' and v['price']<100000000 for v in inventory)
    check(int(page.locator('#results-count').inner_text())==expected,'Body and budget filters combine')
    page.locator('#save-search').click()
    check(page.locator('#saved-searches option').count()==2,'Search can be saved locally')
    page.locator('button[type="reset"]').click();page.wait_for_timeout(60)
    page.locator('#saved-searches').select_option('0');page.wait_for_timeout(60)
    check(page.locator('select[name="body"]').input_value()=='SUV' and page.locator('select[name="budget"]').input_value()=='100000000','Saved search restores filters')
    page.locator('button[type="reset"]').click();page.wait_for_timeout(60)
    page.locator('select[name="sort"]').select_option('price-asc')
    prices=page.locator('.catalogue-grid .vehicle-card:visible').evaluate_all('(cards) => cards.map(c => Number(c.dataset.price))')
    check(prices==sorted(prices),'Price sorting works')
    page.locator('input[name="q"]').fill('no-such-car')
    check(page.locator('.empty-state').is_visible(),'No-result state appears')
    page.locator('#empty-reset').click();page.wait_for_timeout(60)
    check(int(page.locator('#results-count').inner_text())==16,'Reset restores all vehicles')
    page.goto(BASE+'/cars.html?fuel=Hybrid',wait_until='networkidle')
    check(int(page.locator('#results-count').inner_text())==3,'Hybrid filter includes electric cars')
    page.goto(BASE+'/cars.html?saved=1',wait_until='networkidle')
    check(visible_ids(page)==['mercedes-c300'],'Saved vehicles filter works')
    page.goto(BASE+'/cars.html',wait_until='networkidle')
    screenshot(page,'catalogue-desktop.png')
    page.goto(BASE+'/car-details.html?id=bmw-x5',wait_until='networkidle')
    check('BMW X5' in page.locator('h1').inner_text(),'Vehicle has its own detail page')
    check('₦112,000,000' in page.locator('.detail-price').inner_text(),'Detail price matches inventory')
    screenshot(page,'vehicle-desktop.png')
    page.goto(BASE+'/request?kind=import',wait_until='networkidle')
    page.locator('[data-cost]').nth(0).fill('30000.10')
    page.locator('[data-cost]').nth(3).fill('1500.20')
    check(page.locator('#estimated-total').inner_text()=='$31,500.30','Import estimator sums exact cents')
    screenshot(page,'sourcing-desktop.png')
    credentials=json.loads((ROOT/'.local/demo-accounts.json').read_text())
    page.goto(BASE+'/start-order?vehicle=bmw-x5',wait_until='networkidle')
    check(page.url.endswith('/login.html'),'Order requires sign in')
    page.locator('#email').fill(credentials['customer_email']);page.locator('#password').fill(credentials['password'])
    page.locator('button[type="submit"]').click();page.wait_for_url('**/order.html?vehicle=bmw-x5')
    check('BMW X5' in page.locator('.order-vehicle').inner_text(),'Sign in preserves selected vehicle')
    page.locator('#address').fill('1 Fictional Test Road');page.locator('#city').fill('Lagos');page.locator('#state').fill('Lagos')
    page.locator('button[type="submit"]').click();page.wait_for_url('**/order')
    check('BMW X5' in page.locator('.order-summary').inner_text() and '₦112,000,000' in page.locator('.order-summary').inner_text(),'Order checkout shows selected vehicle and server price')
    page.goto(BASE+'/customer-orders',wait_until='networkidle')
    check('BMW X5' in page.locator('body').inner_text(),'Customer order is persisted and visible')
    page.goto(BASE+'/request?kind=import',wait_until='networkidle')
    page.locator('#request-name').fill('Demo Explorer');page.locator('#request-email').fill(credentials['customer_email']);page.locator('#request-vehicle').fill('Toyota RAV4 Hybrid');page.locator('#request-market').select_option('Japan');page.locator('#request-budget').fill('USD 35000')
    page.locator('#request-message').fill('Fictional local browser test: please source a Toyota RAV4 hybrid.')
    page.locator('.request-form button[type="submit"]').click()
    page.locator('.success-panel').wait_for()
    check('saved successfully' in page.locator('.success-panel').inner_text(),'Sourcing request saves successfully')
    page.goto(BASE+'/my-requests',wait_until='networkidle')
    check('Toyota RAV4 Hybrid' in page.locator('.request-list').inner_text(),'Signed-in customer can track own request')
    page.goto(BASE+'/admin-login.html',wait_until='networkidle')
    page.locator('input[name="email"]').fill(credentials['admin_email']);page.locator('input[name="password"]').fill(credentials['password']);page.locator('button[type="submit"]').click();page.wait_for_url('**/admin.html')
    page.goto(BASE+'/admin/enquiries',wait_until='networkidle')
    entry=page.locator('.ops-enquiry').first
    entry.locator('select[name="status"]').select_option('reviewing');entry.locator('button[type="submit"]').click();page.wait_for_load_state('networkidle')
    check(page.locator('.ops-enquiry').first.locator('.ops-status').inner_text()=='Reviewing','Administrator can update enquiry status')
    anon=browser.new_context(viewport={'width':390,'height':844});mobile=anon.new_page();mobile.on('pageerror',lambda error:errors.append(str(error)))
    for path in ['/marvellous.db','/main.go','/.git/config','/.local/demo-accounts.json','/inventory.json','/images/%2e%2e%2fmarvellous.db','/images/..%2fmain.go','/fonts/%2e%2e%2f.local/session-key']:
        check(anon.request.get(BASE+path).status==404,'Protected file blocked: '+path)
    check(anon.request.get(BASE+'/uploads/receipt_10.jpg').status==401,'Anonymous receipt access is blocked')
    check(anon.request.get(BASE+'/admin/enquiries',max_redirects=0).status==303,'Admin enquiry queue requires authentication')
    check(anon.request.post(BASE+'/order',form={'vehicle-id':'bmw-x5'}).status==403,'POST without CSRF token is blocked')
    for path,name in [('/','home-mobile.png'),('/cars.html','catalogue-mobile.png'),('/car-details.html?id=bmw-x5','vehicle-mobile.png'),('/request?kind=import','sourcing-mobile.png'),('/contact.html','contact-mobile.png')]:
        mobile.goto(BASE+path,wait_until='networkidle');screenshot(mobile,name)
    mobile.goto(BASE,wait_until='networkidle');mobile.locator('.menu-toggle').click()
    check(mobile.locator('#nav-links').is_visible(),'Mobile menu opens')
    mobile.locator('#nav-links').get_by_text('Explore vehicles').click();mobile.wait_for_url('**/cars.html')
    check(not errors, 'No browser JavaScript errors: '+str(errors))
    browser.close()
report={'passed':len(checks),'checks':checks,'javascript_errors':errors}
(ROOT/'.local/browser-test-results.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
